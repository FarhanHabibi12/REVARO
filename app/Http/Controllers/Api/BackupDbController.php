<?php

namespace App\Http\Controllers\Api;

use App\Http\Controllers\Controller;
use App\Models\ActivityLog;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;

class BackupDbController extends Controller
{
    /**
     * Enforce strict Super Admin Pemilik access.
     */
    protected function authorizeSuperAdmin(Request $request)
    {
        $user = $request->user() ?: auth('sanctum')->user();
        if (!$user || !method_exists($user, 'isSuperAdminPemilik') || !$user->isSuperAdminPemilik()) {
            abort(403, 'Akses Ditolak: Hanya Super Admin (Pemilik Sistem) yang diizinkan mengelola basis data platform.');
        }
        return $user;
    }

    /**
     * Generate a SQL backup of the MySQL database and download it.
     */
    public function backup(Request $request)
    {
        $user = $this->authorizeSuperAdmin($request);

        $tables = [];
        $result = DB::select('SHOW TABLES');
        $dbName = config('database.connections.mysql.database');
        $key = 'Tables_in_' . $dbName;

        foreach ($result as $row) {
            $tables[] = $row->$key;
        }

        $sql = "-- REVARO Database Backup\n";
        $sql .= "-- Generated by Super Admin: {$user->nama} ({$user->email})\n";
        $sql .= "-- Timestamp: " . date('Y-m-d H:i:s') . "\n\n";
        $sql .= "SET FOREIGN_KEY_CHECKS=0;\n\n";

        foreach ($tables as $table) {
            // Get create table structure
            $createTable = DB::select("SHOW CREATE TABLE `{$table}`");
            $createTableArray = (array)$createTable[0];
            $createStatement = array_values($createTableArray)[1];
            $sql .= "DROP TABLE IF EXISTS `{$table}`;\n";
            $sql .= $createStatement . ";\n\n";

            // Get records
            $rows = DB::table($table)->get();
            foreach ($rows as $row) {
                $rowArray = (array)$row;
                $keys = array_map(function($k) { return "`{$k}`"; }, array_keys($rowArray));
                $values = array_map(function($v) {
                    if (is_null($v)) return 'NULL';
                    return DB::getPdo()->quote($v);
                }, array_values($rowArray));

                $sql .= "INSERT INTO `{$table}` (" . implode(', ', $keys) . ") VALUES (" . implode(', ', $values) . ");\n";
            }
            $sql .= "\n";
        }

        $sql .= "SET FOREIGN_KEY_CHECKS=1;\n";

        ActivityLog::create([
            'user_id' => $user->id,
            'aktivitas' => 'Mengunduh cadangan lengkap basis data platform (.sql)',
            'ip_address' => $request->ip(),
        ]);

        $fileName = 'backup_revaro_' . date('Ymd_His') . '.sql';

        return response($sql, 200, [
            'Content-Type' => 'application/octet-stream',
            'Content-Disposition' => 'attachment; filename="' . $fileName . '"',
        ]);
    }

    /**
     * Restore/overwrite the database from an uploaded SQL backup file.
     * Requires valid Super Admin password confirmation to prevent unauthorized execution.
     */
    public function restore(Request $request)
    {
        $user = $this->authorizeSuperAdmin($request);

        $request->validate([
            'backup_file' => 'required|file|max:51200',
            'admin_password' => 'required|string',
        ], [
            'backup_file.required' => 'Berkas cadangan SQL (.sql) wajib diunggah.',
            'backup_file.max' => 'Ukuran berkas cadangan maksimal 50 MB.',
            'admin_password.required' => 'Kata sandi Super Admin wajib diisi sebagai konfirmasi keamanan.',
        ]);

        if (!Hash::check($request->admin_password, $user->password)) {
            return response()->json([
                'message' => 'Konfirmasi kata sandi Super Admin tidak cocok. Proses restorasi dibatalkan demi keamanan.'
            ], 403);
        }

        $file = $request->file('backup_file');
        $ext = strtolower($file->getClientOriginalExtension());
        if ($ext !== 'sql') {
            return response()->json([
                'message' => 'Format berkas tidak valid. Hanya berkas ekstensi .sql yang diizinkan.'
            ], 422);
        }

        $sql = file_get_contents($file->getRealPath());

        if (empty($sql) || strlen(trim($sql)) < 10) {
            return response()->json(['message' => 'Berkas cadangan SQL kosong atau rusak.'], 400);
        }

        try {
            // Temporary disable foreign key checks
            DB::statement('SET FOREIGN_KEY_CHECKS=0;');

            // Run statements DDL / DML directly
            DB::unprepared($sql);

            DB::statement('SET FOREIGN_KEY_CHECKS=1;');

            ActivityLog::create([
                'user_id' => $user->id,
                'aktivitas' => 'Melakukan restorasi/penimpaan basis data platform dari file: ' . $file->getClientOriginalName(),
                'ip_address' => $request->ip(),
            ]);

            return response()->json([
                'message' => 'Basis data berhasil dipulihkan / di-restore dari berkas cadangan.'
            ]);
        } catch (\Exception $e) {
            try {
                DB::statement('SET FOREIGN_KEY_CHECKS=1;');
            } catch (\Exception $ex) {}

            return response()->json([
                'message' => 'Gagal merestore database: ' . $e->getMessage()
            ], 500);
        }
    }

    /**
     * Clear framework caches (route, config, view, cache).
     */
    public function clearCache(Request $request)
    {
        $user = $this->authorizeSuperAdmin($request);

        try {
            \Illuminate\Support\Facades\Artisan::call('cache:clear');
            \Illuminate\Support\Facades\Artisan::call('config:clear');
            \Illuminate\Support\Facades\Artisan::call('route:clear');
            \Illuminate\Support\Facades\Artisan::call('view:clear');

            ActivityLog::create([
                'user_id' => $user->id,
                'aktivitas' => 'Membersihkan seluruh kompilasi cache framework Laravel (cache, config, route, view)',
                'ip_address' => $request->ip(),
            ]);

            return response()->json([
                'message' => 'Seluruh cache framework Laravel berhasil dibersihkan!'
            ]);
        } catch (\Exception $e) {
            return response()->json([
                'message' => 'Gagal membersihkan cache: ' . $e->getMessage()
            ], 500);
        }
    }

    /**
     * Reset transaction data (orders, transactions, disputes, ratings).
     * Requires Super Admin password confirmation.
     */
    public function resetTransactions(Request $request)
    {
        $user = $this->authorizeSuperAdmin($request);

        $request->validate([
            'admin_password' => 'required|string',
        ], [
            'admin_password.required' => 'Kata sandi Super Admin wajib diisi sebagai konfirmasi keamanan.',
        ]);

        if (!Hash::check($request->admin_password, $user->password)) {
            return response()->json([
                'message' => 'Konfirmasi kata sandi Super Admin tidak cocok. Proses reset dibatalkan.'
            ], 403);
        }

        try {
            DB::statement('SET FOREIGN_KEY_CHECKS=0;');

            DB::table('disputes')->truncate();
            DB::table('rating')->truncate();
            DB::table('transaksi')->truncate();
            DB::table('orders')->truncate();

            DB::statement('SET FOREIGN_KEY_CHECKS=1;');

            ActivityLog::create([
                'user_id' => $user->id,
                'aktivitas' => 'Melakukan reset seluruh riwayat transaksi & order platform',
                'ip_address' => $request->ip(),
            ]);

            return response()->json([
                'message' => 'Seluruh data riwayat transaksi platform telah berhasil di-reset!'
            ]);
        } catch (\Exception $e) {
            try {
                DB::statement('SET FOREIGN_KEY_CHECKS=1;');
            } catch (\Exception $ex) {}

            return response()->json([
                'message' => 'Gagal mengosongkan data transaksi: ' . $e->getMessage()
            ], 500);
        }
    }
}
